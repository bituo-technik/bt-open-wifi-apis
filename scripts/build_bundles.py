# -*- coding: utf-8 -*-
"""Build single-file bundles in dist/ (transport doc + shared business doc [+ protocol reference]).

    py -3 scripts/build_bundles.py

Use them to paste a whole channel into Gitbook, or to hand ONE file to an AI.
dist/ is generated and git-ignored; the docs/ files remain the source of truth.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
DIST = ROOT / "dist"
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

PARTS = {
    "ble-plaintext": ["ble-plaintext/ble-plaintext-api", "ble-common/ble-business-api"],
    "ble-secured": ["ble-secured/ble-secured-api", "ble-secured/ble-advertising", "ble-common/ble-business-api", "ble-secured/crypto-protocol"],
    # Wi-Fi channels: channel page + shared pages it depends on
    "mqtt": ["mqtt/mqtt-api", "ble-common/ble-business-api", "reference/telemetry-payload", "reference/error-codes"],
    "http": ["http/http-api", "ble-common/ble-business-api", "reference/telemetry-payload", "reference/error-codes"],
    "websocket": ["websocket/websocket-api", "ble-common/ble-business-api", "reference/telemetry-payload", "reference/error-codes"],
    "udp": ["udp/udp-api", "reference/telemetry-payload"],
    "modbus-tcp": ["modbus-tcp/modbus-tcp-api"],
    "mdns": ["mdns/mdns-discovery"],
    # everything about the Wi-Fi side in one file
    "open-wifi-all": [
        "overview/open-wifi-overview", "mdns/mdns-discovery", "modbus-tcp/modbus-tcp-api", "http/http-api",
        "websocket/websocket-api", "mqtt/mqtt-api", "udp/udp-api", "reference/telemetry-payload",
        "reference/error-codes", "ble-common/ble-business-api",
    ],
}
BANNER = {
    "zh-CN": "<!-- AUTO-GENERATED by scripts/build_bundles.py from docs/ — do not edit. 合集顺序：{order} -->",
    "en": "<!-- AUTO-GENERATED by scripts/build_bundles.py from docs/ — do not edit. Order: {order} -->",
}


def slug(h):
    h = h.strip().lower().replace("`", "")
    h = re.sub(r"[^\w\- ]", "", h, flags=re.UNICODE)
    return h.replace(" ", "-")


def build(channel, lang):
    stems = PARTS[channel]
    names = {s: s.split("/")[-1] + f".{lang}.md" for s in stems}
    chunks, all_slugs, dup = [], {}, []
    for s in stems:
        text = (DOCS / (s + f".{lang}.md")).read_text(encoding="utf-8")
        incode = False
        for l in text.split("\n"):
            if l.startswith("```"):
                incode = not incode
            m = None if incode else re.match(r"#{1,6}\s+(.*)", l)
            if m:
                sl = slug(m.group(1))
                if sl in all_slugs and all_slugs[sl] != s:
                    dup.append((sl, all_slugs[sl], s))
                all_slugs.setdefault(sl, s)
        chunks.append(text)

    def fix(text):
        # links to another included file -> in-page anchor; links to files not included stay but become plain text refs
        def sub(m):
            label, tgt = m.group(1), m.group(2)
            path, _, frag = tgt.partition("#")
            base = path.split("/")[-1] if path else ""
            if path == "":
                return m.group(0)
            if base in names.values():
                return f"[{label}](#{frag})" if frag else f"[{label}](#{slug(_first_heading(base))})"
            if tgt.startswith(("http://", "https://")):
                return m.group(0)
            # repo-relative file (tools/, spec/, other docs): keep readable, drop the dead link
            return f"{label}（`{Path(path).as_posix().replace('../', '')}`）" if lang == "zh-CN" else f"{label} (`{Path(path).as_posix().replace('../', '')}`)"
        return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", sub, text)

    def _first_heading(base):
        for s, n in names.items():
            if n == base:
                for l in (DOCS / (s + f".{lang}.md")).read_text(encoding="utf-8").split("\n"):
                    m = re.match(r"#\s+(.*)", l)
                    if m:
                        return m.group(1)
        return ""

    body = ("\n\n---\n\n").join(fix(c).strip("\n") for c in chunks)
    order = " → ".join(names.values())
    out = BANNER[lang].format(order=order) + "\n\n" + body + "\n"
    DIST.mkdir(exist_ok=True)
    target = DIST / f"{channel}.complete.{lang}.md"
    target.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {target.relative_to(ROOT)}  {len(out)//1024} KB", ("  duplicate anchors: %d" % len(dup)) if dup else "")
    for d in dup[:6]:
        print("   duplicate anchor", d)
    return dup


total_dup = 0
for ch in PARTS:
    for lang in ("zh-CN", "en"):
        total_dup += len(build(ch, lang))
sys.exit(0)
