#!/usr/bin/env python3
"""Bundle the split web console into one offline HTML (no CDN, no extra JS files).

Edit the split sources, then regenerate:

  py -3 bundle_offline_html.py

Output: web-ble-secured-console.offline.html  (upload this to Cloudflare / Aliyun)
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC_HTML = ROOT / "web-ble-secured-console.html"
OUT_HTML = ROOT / "web-ble-secured-console.offline.html"

MARKER = "<!-- AUTO-GENERATED by bundle_offline_html.py — do not edit. Source: web-ble-secured-console.html -->"


def _need_esbuild() -> str:
    exe = shutil.which("esbuild")
    if exe:
        return exe
    npx = shutil.which("npx")
    if not npx:
        sys.exit("Need Node.js (npx) or esbuild on PATH to bundle the offline HTML.")
    return npx


def extract_module(html: str) -> tuple[str, str]:
    m = re.search(r"<script type=\"module\">\s*(.*?)\s*</script>\s*</body>", html, re.S)
    if not m:
        sys.exit("Could not find <script type=\"module\"> in source HTML")
    js = m.group(1)
    js = re.sub(r'from\s+"(\./[^"?]+)(\?[^"]*)?"', r'from "\1"', js)
    before = html[: m.start()]
    after = html[m.end() :]
    return js, before + "__BUNDLE_SLOT__" + after


def strip_google_fonts(head_html: str) -> str:
    return re.sub(
        r'@import url\("https://fonts\.googleapis\.com/[^"]+"\);\s*',
        "/* Noto Sans omitted in offline build; system fonts used */\n    ",
        head_html,
        count=1,
    )


def main() -> None:
    html = SRC_HTML.read_text(encoding="utf-8")
    js, wrapped = extract_module(html)
    wrapped = strip_google_fonts(wrapped)
    if "<!DOCTYPE html>" in wrapped:
        wrapped = wrapped.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + MARKER, 1)
    wrapped = wrapped.replace(
        "<title>电表加密 BLE 体验（A003 · 完整握手）</title>",
        "<title>电表加密 BLE 体验（A003 · 离线单文件）</title>",
        1,
    )

    esb = _need_esbuild()
    # Entry must sit next to ble_secured_crypto.js so relative imports resolve.
    entry = ROOT / "_offline_entry.js"
    bundled = ROOT / "_offline_bundle.js"
    entry.write_text(js, encoding="utf-8")
    try:
        if Path(esb).name.lower().startswith("esbuild"):
            cmd = [
                esb, str(entry), "--bundle", "--format=iife", "--minify",
                "--legal-comments=none", f"--outfile={bundled}",
            ]
        else:
            cmd = [
                esb, "--yes", "esbuild@0.25.11",
                str(entry), "--bundle", "--format=iife", "--minify",
                "--legal-comments=none", f"--outfile={bundled}",
            ]
        print("run:", " ".join(cmd))
        subprocess.run(cmd, check=True, cwd=ROOT)
        body = bundled.read_text(encoding="utf-8")
    finally:
        entry.unlink(missing_ok=True)
        bundled.unlink(missing_ok=True)

    slot = (
        "<script>\n"
        "/* bundled: ble_secured_crypto.js + help_text.js + vendor (offline) */\n"
        "window.__OFFLINE_BUNDLE__=true;\n"
        + body
        + "\n</script>\n</body>"
    )
    out = wrapped.replace("__BUNDLE_SLOT__", slot)
    OUT_HTML.write_text(out, encoding="utf-8")
    raw = OUT_HTML.stat().st_size
    print(f"wrote {OUT_HTML.name}  {raw} bytes  ({raw/1024:.1f} KB uncompressed)")
    print("Host this one file on any HTTPS static host (Cloudflare R2 / Aliyun OSS). Keep editing the split HTML/JS, then re-run this script.")


if __name__ == "__main__":
    main()
